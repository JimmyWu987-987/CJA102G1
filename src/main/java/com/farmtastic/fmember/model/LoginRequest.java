package com.farmtastic.fmember.model;

public class LoginRequest {
	private String fmemAccLogin;
	private String fmemPwdLogin;
	
	public LoginRequest() {}

	public String getFmemAccLogin() {
		return fmemAccLogin;
	}

	public void setFmemAccLogin(String fmemAccLogin) {
		this.fmemAccLogin = fmemAccLogin;
	}

	public String getFmemPwdLogin() {
		return fmemPwdLogin;
	}

	public void setFmemPwdLogin(String fmemPwdLogin) {
		this.fmemPwdLogin = fmemPwdLogin;
	}

	
	
	
}
